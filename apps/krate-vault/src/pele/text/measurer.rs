//! Ports text/measurer.ts and text/metrics.ts: how wide a run of text is.
//!
//! Pele measures with a canvas where it has one and falls back to a table
//! of Arial advances where it has not (under node, which is how the oracle
//! was made). [`Measure`] is the seam: [`MetricsMeasurer`] is the table,
//! and Vault supplies its own canvas-backed measurer.

#[cfg(target_arch = "wasm32")]
#[allow(unused_imports)]
use krate::prelude::*;

/// Ports `const enum Style`: the flags a span of text is measured and
/// drawn with.
pub mod style {
    pub const BOLD: u32 = 1;
    pub const ITALIC: u32 = 2;
    pub const MONO: u32 = 4;
    pub const SUB: u32 = 8;
    pub const SUP: u32 = 16;
    pub const UNDERLINE: u32 = 32;
}

/// Approximate divisor for CSS font-size="smaller" (`SMALLER`).
pub const SMALLER: f64 = 1.2;

/// Ports `interface TextMeasurer`: the width of `text` at `size` pixels in
/// the given [`style`] flags.
pub trait Measure {
    fn width(&self, text: &str, size: f64, style: u32) -> f64;
}

// Advance widths of printable ASCII in thousandths of an em, two base-36
// digits each (metrics.ts, generated by Pele's scripts/gen-metrics.mjs from Arial).
const REGULAR: &str = "7q7q9vfgfgopij5b9999atg87q997q7qfgfgfgfgfgfgfgfgfgfg7q7qg8g8g8fgs7ijijk2k2ijgzlmk27qdwijfgn5k2lmijlmk2ijgzk2ijq8ijijgz7q7q7qd1fg99fgfgdwfgfg7qfgfg6666dw66n5fgfgfgfg99dw7qfgdwk2dwdwdw9a789ag8";
const BOLD: &str = "7q99d6fgfgopk26m9999atg87q997q7qfgfgfgfgfgfgfgfgfgfg9999g8g8g8gzr3k2k2k2k2ijgzlmk27qfgk2gzn5k2lmijlmk2ijgzk2ijq8ijijgz997q99g8fg99fggzfggzfg99gzgz7q7qfg7qopgzgzgzgzatfg99gzfglmfgfgdwat7satg8";

/// Ports `unpack`.
const fn unpack(packed: &str) -> [u16; 95] {
    let b = packed.as_bytes();
    let mut out = [0u16; 95];
    let mut i = 0;
    while i < 95 {
        out[i] = digit36(b[i * 2]) * 36 + digit36(b[i * 2 + 1]);
        i += 1;
    }
    out
}

const fn digit36(c: u8) -> u16 {
    if c.is_ascii_digit() {
        (c - b'0') as u16
    } else {
        (c - b'a' + 10) as u16
    }
}

static REGULAR_TABLE: [u16; 95] = unpack(REGULAR);
static BOLD_TABLE: [u16; 95] = unpack(BOLD);

/// Ports `isWide` for one UTF-16 code unit.
fn is_wide(c: u32) -> bool {
    (0x1100..=0x115f).contains(&c)
        || (0x2e80..=0xa4cf).contains(&c)
        || (0xac00..=0xd7a3).contains(&c)
        || (0xf900..=0xfaff).contains(&c)
        || (0xfe30..=0xfe4f).contains(&c)
        || (0xff00..=0xff60).contains(&c)
        || (0xffe0..=0xffe6).contains(&c)
        || (0xd800..=0xdbff).contains(&c)
}

/// Ports `isZeroWidth` for one UTF-16 code unit.
fn is_zero_width(c: u32) -> bool {
    c == 0xad
        || (0x300..=0x36f).contains(&c)
        || (0x200b..=0x200f).contains(&c)
        || (0xdc00..=0xdfff).contains(&c)
        || (0xfe00..=0xfe0f).contains(&c)
        || c == 0xfeff
}

/// Ports `metricsMeasurer`: estimates widths from the table of Arial
/// advances. Used where no canvas is available.
#[derive(Debug, Clone, Copy, Default)]
pub struct MetricsMeasurer;

impl Measure for MetricsMeasurer {
    fn width(&self, text: &str, size: f64, style: u32) -> f64 {
        let mono = style & style::MONO != 0;
        let eff = if style & (style::SUB | style::SUP) != 0 {
            size / SMALLER
        } else {
            size
        };
        let table = if style & style::BOLD != 0 {
            &BOLD_TABLE
        } else {
            &REGULAR_TABLE
        };
        let mut units: f64 = 0.0;
        let mut buf = [0u16; 2];
        for ch in text.chars() {
            // JS walks code units: a character beyond the BMP is a high
            // surrogate (wide) and a low one (zero width).
            for &cu in ch.encode_utf16(&mut buf).iter() {
                let c = cu as u32;
                if c < 32 {
                    continue;
                }
                if c < 127 {
                    units += if mono {
                        600.0
                    } else {
                        table[(c - 32) as usize] as f64
                    };
                } else if is_zero_width(c) {
                    continue;
                } else if is_wide(c) {
                    units += if mono { 1200.0 } else { 1000.0 };
                } else {
                    units += if mono { 600.0 } else { 580.0 };
                }
            }
        }
        (units * eff) / 1000.0
    }
}

/// Pele's `metricsMeasurer`, the one shared value.
pub static METRICS: MetricsMeasurer = MetricsMeasurer;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_matches_arial() {
        // 'A' is 667 units in Arial, a space 278.
        assert_eq!(REGULAR_TABLE[(b'A' - 32) as usize], 667);
        assert_eq!(REGULAR_TABLE[0], 278);
        assert_eq!(METRICS.width("AA", 16.0, 0), 2.0 * 667.0 * 16.0 / 1000.0);
        assert_eq!(METRICS.width("\u{4e2d}", 10.0, 0), 10.0);
        assert_eq!(METRICS.width("\u{1f600}", 10.0, 0), 10.0);
    }
}
