//! Generates the core-module glue for threaded apps (IC-929).
//!
//! A threaded Krate app is a core module over a shared memory, not a
//! component: the component model has no way to share one memory between
//! instances on several threads, and wit-component refuses a module that
//! imports a shared memory ("mismatch in the shared flag for memories"). So
//! the runtime links such a module itself. Its imports are exactly the ones
//! wit-bindgen gives a component's core module -- `krate:fs/files@0.1.0`
//! `[method]file.read` and so on, in the canonical ABI -- and this script
//! writes, for every function of the Phase 4 `gui` world, the host function
//! that lifts its arguments out of the shared memory into the Rust types
//! wasmtime's bindgen generated, calls the same `Host` trait method the
//! component path calls, and lowers the result back.
//!
//! Output: `$OUT_DIR/core_glue.rs`, included by `src/core_app.rs`.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::path::PathBuf;

use heck::{ToShoutySnakeCase, ToSnakeCase, ToUpperCamelCase};
use wit_parser::{
    Function, FunctionKind, Handle, InterfaceId, Resolve, SizeAlign, Type, TypeDefKind, TypeId,
    TypeOwner, WorldItem,
};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let wit = manifest.join("../../wit/krate/phase4");
    println!("cargo:rerun-if-changed={}", wit.display());
    println!("cargo:rerun-if-changed=build.rs");
    // The interfaces Phase 3 has: any other gui interface is Phase 4's own
    // and lives in the Phase 4 bindings (see `home`).
    let phase3 = manifest.join("../../wit/krate/phase3");
    println!("cargo:rerun-if-changed={}", phase3.display());
    let mut old = Resolve::default();
    let (old_pkg, _) = old.push_dir(&phase3).expect("the Phase 3 WIT parses");
    let old_world = old
        .select_world(&[old_pkg], Some("gui"))
        .expect("the Phase 3 gui world");
    let names: HashSet<String> = old.worlds[old_world]
        .imports
        .values()
        .filter_map(|item| match item {
            WorldItem::Interface { id, .. } => {
                let i = &old.interfaces[*id];
                let pkg = &old.packages[i.package?].name;
                Some(format!("{}/{}", pkg.name, i.name.as_ref()?))
            }
            _ => None,
        })
        .collect();
    PHASE3_INTERFACES.set(names).expect("set once");
    let mut resolve = Resolve::default();
    let (pkg, _) = resolve.push_dir(&wit).expect("the Phase 4 WIT parses");
    let world = resolve
        .select_world(&[pkg], Some("gui"))
        .expect("the gui world");
    let mut sizes = SizeAlign::default();
    sizes.fill(&resolve);
    let mut g = Gen {
        r: &resolve,
        sizes,
        types: String::new(),
        funcs: String::new(),
        done: HashSet::new(),
        fam: "crate::phase4_gui_bindings",
    };
    let imports: Vec<(String, InterfaceId)> = resolve.worlds[world]
        .imports
        .iter()
        .filter_map(|(key, item)| match item {
            WorldItem::Interface { id, .. } => Some((resolve.name_world_key(key), *id)),
            _ => None,
        })
        .collect();
    let mut count = 0;
    for (name, id) in &imports {
        count += g.interface(name, *id);
    }
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("core_glue.rs");
    let text = format!(
        "// Generated by crates/runtime/build.rs from wit/krate/phase4. Do not edit.\n\
         #[allow(clippy::all, unused_variables, unused_mut, unused_parens, non_snake_case, \
         unreachable_code, dead_code)]\n\
         pub(crate) mod glue {{\n\
         use super::abi::*;\n\
         use wasmtime::{{Val, ValType}};\n\
         /// Functions the glue links.\n\
         pub(crate) const FUNCTIONS: usize = {count};\n\
         pub(crate) fn add_to_linker(linker: &mut wasmtime::Linker<super::Thread>, st: &std::sync::Arc<super::Shared>) -> wasmtime::Result<()> {{\n\
         let engine = linker.engine().clone();\n{}\nOk(())\n}}\n{}\n}}\n",
        g.funcs, g.types
    );
    std::fs::write(out, text).unwrap();
}

struct Gen<'a> {
    r: &'a Resolve,
    sizes: SizeAlign,
    types: String,
    funcs: String,
    done: HashSet<(TypeId, &'static str)>,
    /// The bindgen module family the function being generated belongs to;
    /// a type's Rust path depends on it (phase 3's ui types are not phase
    /// 4's).
    fam: &'static str,
}

/// The gui interfaces the Phase 3 world imports, as `pkg/interface`.
static PHASE3_INTERFACES: std::sync::OnceLock<HashSet<String>> = std::sync::OnceLock::new();

/// Which bindgen module an interface's Rust lives in, and which host serves it
/// -- the same choices `Runtime::phase4_gui_linker` makes: the Phase 4
/// bindings for an interface Phase 4 changed (listed) or added (anything
/// Phase 3 does not import, so a new Phase 4 interface needs no entry here).
fn home(iface: &str) -> (&'static str, &'static str) {
    const PHASE4: &[&str] = &[
        "ui/types",
        "ui/tree",
        "ui/dialog",
        "ui/events",
        "ui/print",
        "ui/pointer",
        "ui/touch",
        "ui/text-entry",
        "ui/screen",
        "gfx/canvas-images",
        "gpu/types",
        "gpu/gpu",
        "audio/playback-queue",
        "speech/synthesis",
    ];
    let pkg = iface.split('/').next().unwrap_or("");
    let phase2 = matches!(
        pkg,
        "io" | "fs" | "net" | "time" | "locale" | "resources" | "store" | "random" | "process"
    );
    if phase2 {
        ("crate::phase2_bindings", "phase2")
    } else if PHASE4.contains(&iface)
        || PHASE3_INTERFACES
            .get()
            .is_some_and(|phase3| !phase3.contains(iface))
    {
        ("crate::phase4_gui_bindings", "phase3_gui")
    } else {
        ("crate::phase3_gui_bindings", "phase3_gui")
    }
}

/// Interfaces a worker thread may not call: they reach the window and
/// AppKit, which live on the main thread.
///
/// Audio is not among them: a sound engine feeds its stream from a thread of
/// its own (cpal's Krate host, IC-932), and the host's streams are device
/// handles that any thread may start, stop and write to. Nor is the GPU, its
/// surface included: an engine renders and presents from a worker (Bevy's
/// multi-threaded executor), and a frame presented there is lowered to the
/// window by the main thread on its next turn (`WorkerScreen`).
fn main_thread_only(iface: &str, _func: &str) -> bool {
    let pkg = iface.split('/').next().unwrap_or("");
    matches!(pkg, "ui" | "gfx" | "camera" | "speech")
}

fn fam_tag(fam: &str) -> &'static str {
    match fam {
        "crate::phase2_bindings" => "p2",
        "crate::phase3_gui_bindings" => "p3",
        _ => "p4",
    }
}

fn rust_ident(name: &str) -> String {
    let s = name.to_snake_case();
    match s.as_str() {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "self" | "static" | "struct" | "super" | "trait"
        | "true" | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await" | "dyn"
        | "abstract" | "become" | "box" | "do" | "final" | "macro" | "override" | "priv"
        | "typeof" | "unsized" | "virtual" | "yield" | "try" | "gen" => format!("{s}_"),
        _ => s,
    }
}

fn camel(name: &str) -> String {
    name.to_upper_camel_case()
}

#[derive(Clone, Copy, PartialEq, Debug)]
enum Flat {
    I32,
    I64,
    F32,
    F64,
}

impl Flat {
    fn valtype(self) -> &'static str {
        match self {
            Flat::I32 => "ValType::I32",
            Flat::I64 => "ValType::I64",
            Flat::F32 => "ValType::F32",
            Flat::F64 => "ValType::F64",
        }
    }
}

fn join(a: Flat, b: Flat) -> Flat {
    match (a, b) {
        _ if a == b => a,
        (Flat::I32, Flat::F32) | (Flat::F32, Flat::I32) => Flat::I32,
        _ => Flat::I64,
    }
}

impl<'a> Gen<'a> {
    fn iface_name(&self, id: InterfaceId) -> String {
        let i = &self.r.interfaces[id];
        let pkg = &self.r.packages[i.package.unwrap()].name;
        format!("{}/{}", pkg.name, i.name.as_ref().unwrap())
    }

    fn iface_path(&self, id: InterfaceId) -> String {
        let name = self.iface_name(id);
        let (home_root, _) = home(&name);
        // As seen from the current family's bindgen.
        let root = match self.fam {
            "crate::phase2_bindings" => "crate::phase2_bindings",
            "crate::phase3_gui_bindings" => {
                if home_root == "crate::phase2_bindings" {
                    home_root
                } else {
                    "crate::phase3_gui_bindings"
                }
            }
            _ => home_root,
        };
        let i = &self.r.interfaces[id];
        let pkg = &self.r.packages[i.package.unwrap()].name;
        format!(
            "{root}::{}::{}::{}",
            rust_ident(&pkg.namespace),
            rust_ident(&pkg.name),
            rust_ident(i.name.as_ref().unwrap())
        )
    }

    fn resolve_alias(&self, ty: &Type) -> Type {
        let mut t = *ty;
        while let Type::Id(id) = t {
            match &self.r.types[id].kind {
                TypeDefKind::Type(inner) => t = *inner,
                _ => break,
            }
        }
        t
    }

    fn named_path(&self, id: TypeId) -> String {
        let td = &self.r.types[id];
        let owner = match td.owner {
            TypeOwner::Interface(i) => self.iface_path(i),
            _ => panic!("a type outside an interface"),
        };
        format!("{owner}::{}", camel(td.name.as_ref().unwrap()))
    }

    fn rust_ty(&self, ty: &Type) -> String {
        match self.resolve_alias(ty) {
            Type::Bool => "bool".into(),
            Type::U8 => "u8".into(),
            Type::U16 => "u16".into(),
            Type::U32 => "u32".into(),
            Type::U64 => "u64".into(),
            Type::S8 => "i8".into(),
            Type::S16 => "i16".into(),
            Type::S32 => "i32".into(),
            Type::S64 => "i64".into(),
            Type::F32 => "f32".into(),
            Type::F64 => "f64".into(),
            Type::Char => "char".into(),
            Type::String => "String".into(),
            Type::ErrorContext => panic!("error-context"),
            Type::Id(id) => match &self.r.types[id].kind {
                TypeDefKind::Record(_)
                | TypeDefKind::Variant(_)
                | TypeDefKind::Enum(_)
                | TypeDefKind::Flags(_) => self.named_path(id),
                TypeDefKind::List(t) => format!("Vec<{}>", self.rust_ty(t)),
                TypeDefKind::Option(t) => format!("Option<{}>", self.rust_ty(t)),
                TypeDefKind::Result(r) => format!(
                    "Result<{}, {}>",
                    r.ok.as_ref()
                        .map(|t| self.rust_ty(t))
                        .unwrap_or("()".into()),
                    r.err
                        .as_ref()
                        .map(|t| self.rust_ty(t))
                        .unwrap_or("()".into())
                ),
                TypeDefKind::Tuple(t) => {
                    let parts: Vec<String> = t.types.iter().map(|t| self.rust_ty(t)).collect();
                    if parts.len() == 1 {
                        format!("({},)", parts[0])
                    } else {
                        format!("({})", parts.join(", "))
                    }
                }
                TypeDefKind::Handle(Handle::Own(r)) | TypeDefKind::Handle(Handle::Borrow(r)) => {
                    format!("wasmtime::component::Resource<{}>", self.named_path(*r))
                }
                other => panic!("unsupported type {other:?}"),
            },
        }
    }

    fn flat(&self, ty: &Type) -> Vec<Flat> {
        match self.resolve_alias(ty) {
            Type::Bool
            | Type::U8
            | Type::U16
            | Type::U32
            | Type::S8
            | Type::S16
            | Type::S32
            | Type::Char => vec![Flat::I32],
            Type::U64 | Type::S64 => vec![Flat::I64],
            Type::F32 => vec![Flat::F32],
            Type::F64 => vec![Flat::F64],
            Type::String => vec![Flat::I32, Flat::I32],
            Type::ErrorContext => vec![Flat::I32],
            Type::Id(id) => match &self.r.types[id].kind {
                TypeDefKind::Record(r) => r.fields.iter().flat_map(|f| self.flat(&f.ty)).collect(),
                TypeDefKind::Tuple(t) => t.types.iter().flat_map(|t| self.flat(t)).collect(),
                TypeDefKind::List(_) => vec![Flat::I32, Flat::I32],
                TypeDefKind::Handle(_) => vec![Flat::I32],
                TypeDefKind::Enum(_) => vec![Flat::I32],
                TypeDefKind::Flags(f) => vec![Flat::I32; f.flags.len().div_ceil(32).max(1)],
                TypeDefKind::Variant(_) | TypeDefKind::Option(_) | TypeDefKind::Result(_) => {
                    let mut out = vec![Flat::I32];
                    for t in self.cases(&Type::Id(id)).into_iter().flatten() {
                        for (i, f) in self.flat(&t).into_iter().enumerate() {
                            if i + 1 < out.len() {
                                out[i + 1] = join(out[i + 1], f);
                            } else {
                                out.push(f);
                            }
                        }
                    }
                    out
                }
                other => panic!("unsupported type {other:?}"),
            },
        }
    }

    /// The payload types of a variant-shaped type, in case order.
    fn cases(&self, ty: &Type) -> Vec<Option<Type>> {
        let Type::Id(id) = self.resolve_alias(ty) else {
            return vec![];
        };
        match &self.r.types[id].kind {
            TypeDefKind::Variant(v) => v.cases.iter().map(|c| c.ty).collect(),
            TypeDefKind::Option(t) => vec![None, Some(*t)],
            TypeDefKind::Result(r) => vec![r.ok, r.err],
            _ => vec![],
        }
    }

    fn size(&self, ty: &Type) -> usize {
        self.sizes.size(ty).size_wasm32()
    }

    fn align(&self, ty: &Type) -> usize {
        self.sizes.align(ty).align_wasm32()
    }

    /// A unique suffix for the helpers of one type.
    fn key(&mut self, ty: &Type) -> String {
        match self.resolve_alias(ty) {
            Type::Bool => "bool".into(),
            Type::U8 => "u8".into(),
            Type::U16 => "u16".into(),
            Type::U32 => "u32".into(),
            Type::U64 => "u64".into(),
            Type::S8 => "s8".into(),
            Type::S16 => "s16".into(),
            Type::S32 => "s32".into(),
            Type::S64 => "s64".into(),
            Type::F32 => "f32".into(),
            Type::F64 => "f64".into(),
            Type::Char => "char".into(),
            Type::String => "string".into(),
            Type::ErrorContext => panic!("error-context"),
            Type::Id(id) => {
                self.emit_type(id);
                format!("t{}_{}", id.index(), fam_tag(self.fam))
            }
        }
    }

    /// Discriminant byte size for a type with `n` cases.
    fn disc_size(n: usize) -> usize {
        if n <= 1 << 8 {
            1
        } else if n <= 1 << 16 {
            2
        } else {
            4
        }
    }

    fn disc_load(n: usize) -> &'static str {
        match Self::disc_size(n) {
            1 => "load_u8(cx, a)? as u32",
            2 => "load_u16(cx, a)? as u32",
            _ => "load_u32(cx, a)?",
        }
    }

    fn disc_store(n: usize) -> &'static str {
        match Self::disc_size(n) {
            1 => "put_u8(cx, a, d as u8)?",
            2 => "put_u16(cx, a, d as u16)?",
            _ => "put_u32(cx, a, d)?",
        }
    }

    /// Emit load/store/lift/lower for one named or anonymous type.
    fn emit_type(&mut self, id: TypeId) {
        if !self.done.insert((id, self.fam)) {
            return;
        }
        let ty = Type::Id(id);
        let rt = self.rust_ty(&ty);
        let k = format!("t{}_{}", id.index(), fam_tag(self.fam));
        let kind = self.r.types[id].kind.clone();
        let load: String;
        let store: String;
        let lift: String;
        let lower: String;
        match &kind {
            TypeDefKind::Type(t) => {
                // An alias: delegate.
                let inner = self.key(t);
                load = format!("load_{inner}(cx, a)");
                store = format!("store_{inner}(cx, rl, a, v)");
                lift = format!("lift_{inner}(cx, f)");
                lower = format!("lower_{inner}(cx, rl, v, out)");
            }
            TypeDefKind::Record(r) => {
                let tys: Vec<Type> = r.fields.iter().map(|f| f.ty).collect();
                let offs: Vec<usize> = self
                    .sizes
                    .field_offsets(tys.iter())
                    .into_iter()
                    .map(|(o, _)| o.size_wasm32())
                    .collect();
                let mut fl = String::new();
                let mut fs = String::new();
                let mut fli = String::new();
                let mut flo = String::new();
                let mut at = 0;
                for (i, field) in r.fields.iter().enumerate() {
                    let fk = self.key(&field.ty);
                    let name = rust_ident(&field.name);
                    let n = self.flat(&field.ty).len();
                    let _ = write!(fl, "{name}: load_{fk}(cx, a + {})?, ", offs[i]);
                    let _ = write!(fs, "store_{fk}(cx, rl, a + {}, v.{name})?; ", offs[i]);
                    let _ = write!(fli, "{name}: lift_{fk}(cx, &f[{at}..{}])?, ", at + n);
                    let _ = write!(flo, "lower_{fk}(cx, rl, v.{name}, out)?; ");
                    at += n;
                }
                load = format!("Ok({rt} {{ {fl} }})");
                store = format!("{fs} Ok(())");
                lift = format!("Ok({rt} {{ {fli} }})");
                lower = format!("{flo} Ok(())");
            }
            TypeDefKind::Tuple(t) => {
                let offs: Vec<usize> = self
                    .sizes
                    .field_offsets(t.types.iter())
                    .into_iter()
                    .map(|(o, _)| o.size_wasm32())
                    .collect();
                let mut fl = Vec::new();
                let mut fs = String::new();
                let mut fli = Vec::new();
                let mut flo = String::new();
                let mut at = 0;
                for (i, et) in t.types.iter().enumerate() {
                    let ek = self.key(et);
                    let n = self.flat(et).len();
                    fl.push(format!("load_{ek}(cx, a + {})?", offs[i]));
                    let _ = write!(fs, "store_{ek}(cx, rl, a + {}, v.{i})?; ", offs[i]);
                    fli.push(format!("lift_{ek}(cx, &f[{at}..{}])?", at + n));
                    let _ = write!(flo, "lower_{ek}(cx, rl, v.{i}, out)?; ");
                    at += n;
                }
                let comma = if t.types.len() == 1 { "," } else { "" };
                load = format!("Ok(({}{comma}))", fl.join(", "));
                store = format!("{fs} Ok(())");
                lift = format!("Ok(({}{comma}))", fli.join(", "));
                lower = format!("{flo} Ok(())");
            }
            TypeDefKind::List(t) => {
                let ek = self.key(t);
                let es = self.size(t);
                let ea = self.align(t);
                if matches!(self.resolve_alias(t), Type::U8) {
                    load = "let p = load_u32(cx, a)?; let n = load_u32(cx, a + 4)?; cx.bytes(p, n)"
                        .into();
                    store = "let n = v.len() as u32; let p = rl.alloc(n, 1)?; cx.write(p, &v)?; put_u32(cx, a, p)?; put_u32(cx, a + 4, n)".into();
                    lift = "cx.bytes(i32_of(&f[0]) as u32, i32_of(&f[1]) as u32)".into();
                    lower = "let n = v.len() as u32; let p = rl.alloc(n, 1)?; cx.write(p, &v)?; out.push(Val::I32(p as i32)); out.push(Val::I32(n as i32)); Ok(())".into();
                } else {
                    load = format!(
                        "let p = load_u32(cx, a)?; let n = load_u32(cx, a + 4)?; cx.check(p, n.saturating_mul({es}))?; \
                         let mut out = Vec::with_capacity(n as usize); for i in 0..n {{ out.push(load_{ek}(cx, p + i * {es})?); }} Ok(out)"
                    );
                    store = format!(
                        "let n = v.len() as u32; let p = rl.alloc(n * {es}, {ea})?; \
                         for (i, e) in v.into_iter().enumerate() {{ store_{ek}(cx, rl, p + i as u32 * {es}, e)?; }} \
                         put_u32(cx, a, p)?; put_u32(cx, a + 4, n)"
                    );
                    lift = format!(
                        "let p = i32_of(&f[0]) as u32; let n = i32_of(&f[1]) as u32; cx.check(p, n.saturating_mul({es}))?; \
                         let mut out = Vec::with_capacity(n as usize); for i in 0..n {{ out.push(load_{ek}(cx, p + i * {es})?); }} Ok(out)"
                    );
                    lower = format!(
                        "let n = v.len() as u32; let p = rl.alloc(n * {es}, {ea})?; \
                         for (i, e) in v.into_iter().enumerate() {{ store_{ek}(cx, rl, p + i as u32 * {es}, e)?; }} \
                         out.push(Val::I32(p as i32)); out.push(Val::I32(n as i32)); Ok(())"
                    );
                }
            }
            TypeDefKind::Handle(h) => {
                let own = matches!(h, Handle::Own(_));
                let make = if own { "new_own" } else { "new_borrow" };
                load = format!("Ok(wasmtime::component::Resource::{make}(load_u32(cx, a)?))");
                store = "put_u32(cx, a, v.rep())".into();
                lift = format!("Ok(wasmtime::component::Resource::{make}(i32_of(&f[0]) as u32))");
                lower = "out.push(Val::I32(v.rep() as i32)); Ok(())".into();
            }
            TypeDefKind::Enum(e) => {
                let n = e.cases.len();
                let mut ml = String::new();
                let mut ms = String::new();
                for (i, c) in e.cases.iter().enumerate() {
                    let _ = write!(ml, "{i} => {rt}::{}, ", camel(&c.name));
                    let _ = write!(ms, "{rt}::{} => {i}, ", camel(&c.name));
                }
                let dl = Self::disc_load(n);
                let ds = Self::disc_store(n);
                load =
                    format!("let d = {dl}; Ok(match d {{ {ml} _ => return Err(bad(\"enum\")) }})");
                store = format!("let d: u32 = match v {{ {ms} }}; {ds}; Ok(())");
                lift = format!("let d = i32_of(&f[0]) as u32; Ok(match d {{ {ml} _ => return Err(bad(\"enum\")) }})");
                lower = format!(
                    "let d: u32 = match v {{ {ms} }}; out.push(Val::I32(d as i32)); Ok(())"
                );
            }
            TypeDefKind::Flags(fl) => {
                let words = fl.flags.len().div_ceil(32).max(1);
                let bytes = match fl.flags.len() {
                    0..=8 => 1,
                    9..=16 => 2,
                    _ => 4 * words,
                };
                let mut from = String::new();
                let mut to = String::new();
                for (i, flag) in fl.flags.iter().enumerate() {
                    let c = flag.name.to_shouty_snake_case();
                    let (w, b) = (i / 32, i % 32);
                    let _ = write!(
                        from,
                        "if w[{w}] & (1u32 << {b}) != 0 {{ x |= {rt}::{c}; }} "
                    );
                    let _ = write!(to, "if v.contains({rt}::{c}) {{ w[{w}] |= 1u32 << {b}; }} ");
                }
                let read = match bytes {
                    1 => "w[0] = load_u8(cx, a)? as u32;".to_string(),
                    2 => "w[0] = load_u16(cx, a)? as u32;".to_string(),
                    _ => (0..words)
                        .map(|i| format!("w[{i}] = load_u32(cx, a + {})?;", i * 4))
                        .collect(),
                };
                let write = match bytes {
                    1 => "put_u8(cx, a, w[0] as u8)?;".to_string(),
                    2 => "put_u16(cx, a, w[0] as u16)?;".to_string(),
                    _ => (0..words)
                        .map(|i| format!("put_u32(cx, a + {}, w[{i}])?;", i * 4))
                        .collect(),
                };
                load = format!(
                    "let mut w = [0u32; {words}]; {read} let mut x = {rt}::empty(); {from} Ok(x)"
                );
                store = format!("let mut w = [0u32; {words}]; {to} {write} Ok(())");
                let lifts: String = (0..words)
                    .map(|i| format!("w[{i}] = i32_of(&f[{i}]) as u32;"))
                    .collect();
                let lowers: String = (0..words)
                    .map(|i| format!("out.push(Val::I32(w[{i}] as i32));"))
                    .collect();
                lift = format!(
                    "let mut w = [0u32; {words}]; {lifts} let mut x = {rt}::empty(); {from} Ok(x)"
                );
                lower = format!("let mut w = [0u32; {words}]; {to} {lowers} Ok(())");
            }
            TypeDefKind::Variant(_) | TypeDefKind::Option(_) | TypeDefKind::Result(_) => {
                let cases = self.cases(&ty);
                let n = cases.len();
                let ds = Self::disc_size(n);
                let max_align = cases
                    .iter()
                    .flatten()
                    .map(|t| self.align(t))
                    .max()
                    .unwrap_or(1)
                    .max(ds);
                let payload = ds.next_multiple_of(max_align);
                let joined = self.flat(&ty);
                // Case constructors and patterns.
                let names: Vec<(String, String)> = match &kind {
                    TypeDefKind::Variant(v) => v
                        .cases
                        .iter()
                        .map(|c| {
                            let p = format!("{rt}::{}", camel(&c.name));
                            (p.clone(), p)
                        })
                        .collect(),
                    TypeDefKind::Option(_) => {
                        vec![
                            ("None".into(), "None".into()),
                            ("Some".into(), "Some".into()),
                        ]
                    }
                    TypeDefKind::Result(_) => {
                        vec![("Ok".into(), "Ok".into()), ("Err".into(), "Err".into())]
                    }
                    _ => unreachable!(),
                };
                let unit_payload = |kind: &TypeDefKind, i: usize| -> bool {
                    // Result's empty sides are `()` in Rust, not absent.
                    matches!(kind, TypeDefKind::Result(_)) && cases[i].is_none()
                };
                let mut ml = String::new();
                let mut mli = String::new();
                let mut ms = String::new();
                let mut mlo = String::new();
                for (i, case) in cases.iter().enumerate() {
                    let (ctor, pat) = &names[i];
                    match case {
                        Some(t) => {
                            let ck = self.key(t);
                            let cflat = self.flat(t);
                            let coerce: Vec<String> = cflat
                                .iter()
                                .enumerate()
                                .map(|(j, want)| {
                                    format!("coerce(&f[{}], {})", j + 1, want.valtype())
                                })
                                .collect();
                            let _ = write!(ml, "{i} => {ctor}(load_{ck}(cx, a + {payload})?), ");
                            let _ = write!(
                                mli,
                                "{i} => {{ let p = [{}]; {ctor}(lift_{ck}(cx, &p)?) }} ",
                                coerce.join(", ")
                            );
                            let _ = write!(
                                ms,
                                "{pat}(x) => {{ let d = {i}u32; {}; store_{ck}(cx, rl, a + {payload}, x)?; }} ",
                                Self::disc_store(n)
                            );
                            let pads: String = joined
                                .iter()
                                .skip(1 + cflat.len())
                                .map(|j| format!("out.push(zero({}));", j.valtype()))
                                .collect();
                            let widen: String = joined
                                .iter()
                                .skip(1)
                                .take(cflat.len())
                                .enumerate()
                                .map(|(j, jt)| {
                                    format!("out.push(widen(&tmp[{j}], {}));", jt.valtype())
                                })
                                .collect();
                            let _ = write!(
                                mlo,
                                "{pat}(x) => {{ out.push(Val::I32({i})); let mut tmp = Vec::new(); lower_{ck}(cx, rl, x, &mut tmp)?; {widen} {pads} }} "
                            );
                        }
                        None => {
                            let (c, p) = if unit_payload(&kind, i) {
                                (format!("{ctor}(())"), format!("{pat}(())"))
                            } else {
                                (ctor.clone(), pat.clone())
                            };
                            let _ = write!(ml, "{i} => {c}, ");
                            let _ = write!(mli, "{i} => {c}, ");
                            let _ = write!(
                                ms,
                                "{p} => {{ let d = {i}u32; {}; }} ",
                                Self::disc_store(n)
                            );
                            let pads: String = joined
                                .iter()
                                .skip(1)
                                .map(|j| format!("out.push(zero({}));", j.valtype()))
                                .collect();
                            let _ = write!(mlo, "{p} => {{ out.push(Val::I32({i})); {pads} }} ");
                        }
                    }
                }
                let dl = Self::disc_load(n);
                load = format!(
                    "let d = {dl}; Ok(match d {{ {ml} _ => return Err(bad(\"variant\")) }})"
                );
                store = format!("match v {{ {ms} }} Ok(())");
                lift = format!("let d = i32_of(&f[0]) as u32; Ok(match d {{ {mli} _ => return Err(bad(\"variant\")) }})");
                lower = format!("match v {{ {mlo} }} Ok(())");
            }
            TypeDefKind::Resource => return,
            other => panic!("unsupported type {other:?}"),
        }
        let _ = writeln!(
            self.types,
            "pub(crate) fn load_{k}(cx: &Cx, a: u32) -> wasmtime::Result<{rt}> {{ {load} }}\n\
             pub(crate) fn store_{k}(cx: &Cx, rl: &mut dyn Realloc, a: u32, v: {rt}) -> wasmtime::Result<()> {{ {store} }}\n\
             pub(crate) fn lift_{k}(cx: &Cx, f: &[Val]) -> wasmtime::Result<{rt}> {{ {lift} }}\n\
             pub(crate) fn lower_{k}(cx: &Cx, rl: &mut dyn Realloc, v: {rt}, out: &mut Vec<Val>) -> wasmtime::Result<()> {{ {lower} }}"
        );
    }

    /// Emit the linker entries for one interface. Returns how many.
    fn interface(&mut self, key: &str, id: InterfaceId) -> usize {
        let iface = self.iface_name(id);
        let (root, accessor) = home(&iface);
        self.fam = root;
        let path = self.iface_path(id);
        let mut n = 0;
        let funcs: Vec<Function> = self.r.interfaces[id].functions.values().cloned().collect();
        for func in &funcs {
            self.function(key, &iface, &path, accessor, func);
            n += 1;
        }
        // Resource drops.
        let resources: BTreeMap<String, TypeId> = self.r.interfaces[id]
            .types
            .iter()
            .filter(|(_, t)| matches!(self.r.types[**t].kind, TypeDefKind::Resource))
            .map(|(name, t)| (name.clone(), *t))
            .collect();
        for (name, _) in resources {
            let c = camel(&name);
            let only_main = main_thread_only(&iface, "");
            let _ = writeln!(
                self.funcs,
                "{{ let st = st.clone(); linker.func_new({key:?}, \"[resource-drop]{name}\", \
                 wasmtime::FuncType::new(&engine, [ValType::I32], []), move |caller, args, _rets| {{ \
                 let r = wasmtime::component::Resource::<{path}::{c}>::new_own(i32_of(&args[0]) as u32); \
                 let mut h = st.host({only_main}, \"{iface}\")?; \
                 {path}::Host{c}::drop(h.{accessor}(), r) }})?; }}"
            );
            n += 1;
        }
        n
    }

    fn function(&mut self, key: &str, iface: &str, path: &str, accessor: &str, func: &Function) {
        let sig = self
            .r
            .wasm_signature(wit_parser::abi::AbiVariant::GuestImport, func);
        let flat_ty = |t: &wit_parser::abi::WasmType| match t {
            wit_parser::abi::WasmType::I32
            | wit_parser::abi::WasmType::Pointer
            | wit_parser::abi::WasmType::Length => "ValType::I32",
            wit_parser::abi::WasmType::I64 | wit_parser::abi::WasmType::PointerOrI64 => {
                "ValType::I64"
            }
            wit_parser::abi::WasmType::F32 => "ValType::F32",
            wit_parser::abi::WasmType::F64 => "ValType::F64",
        };
        let params: Vec<&str> = sig.params.iter().map(flat_ty).collect();
        let results: Vec<&str> = sig.results.iter().map(flat_ty).collect();
        // The Rust call.
        let (trait_, method) = match &func.kind {
            FunctionKind::Freestanding | FunctionKind::AsyncFreestanding => {
                ("Host".to_string(), rust_ident(&func.name))
            }
            FunctionKind::Method(r) | FunctionKind::AsyncMethod(r) => {
                let rn = self.r.types[*r].name.clone().unwrap();
                let m = func.name.split('.').nth(1).unwrap_or(&func.name);
                (format!("Host{}", camel(&rn)), rust_ident(m))
            }
            FunctionKind::Static(r) | FunctionKind::AsyncStatic(r) => {
                let rn = self.r.types[*r].name.clone().unwrap();
                let m = func.name.split('.').nth(1).unwrap_or(&func.name);
                (format!("Host{}", camel(&rn)), rust_ident(m))
            }
            FunctionKind::Constructor(r) => {
                let rn = self.r.types[*r].name.clone().unwrap();
                (format!("Host{}", camel(&rn)), "new".to_string())
            }
        };
        let mut lifts = String::new();
        let mut args = Vec::new();
        if sig.indirect_params {
            let tys: Vec<Type> = func.params.iter().map(|(_, t)| *t).collect();
            let offs: Vec<usize> = self
                .sizes
                .field_offsets(tys.iter())
                .into_iter()
                .map(|(o, _)| o.size_wasm32())
                .collect();
            let _ = write!(lifts, "let base = i32_of(&args[0]) as u32; ");
            for (i, (_, t)) in func.params.iter().enumerate() {
                let k = self.key(t);
                let _ = write!(lifts, "let a{i} = load_{k}(&cx, base + {})?; ", offs[i]);
                args.push(format!("a{i}"));
            }
        } else {
            let mut at = 0;
            for (i, (_, t)) in func.params.iter().enumerate() {
                let k = self.key(t);
                let n = self.flat(t).len();
                let _ = write!(
                    lifts,
                    "let a{i} = lift_{k}(&cx, &args[{at}..{}])?; ",
                    at + n
                );
                args.push(format!("a{i}"));
                at += n;
            }
        }
        let lower = match &func.result {
            None => String::new(),
            Some(t) => {
                let k = self.key(t);
                if sig.retptr {
                    let at = sig.params.len() - 1;
                    format!(
                        "let rp = i32_of(&args[{at}]) as u32; let mut rl = st.realloc(&mut caller); store_{k}(&cx, &mut rl, rp, r)?;"
                    )
                } else {
                    format!(
                        "let mut rl = st.realloc(&mut caller); let mut out = Vec::new(); lower_{k}(&cx, &mut rl, r, &mut out)?; rets[0] = out.into_iter().next().unwrap_or(Val::I32(0));"
                    )
                }
            }
        };
        let only_main = main_thread_only(iface, &func.name);
        let call_args = if args.is_empty() {
            String::new()
        } else {
            format!(", {}", args.join(", "))
        };
        // A GPU present's frame pacing, and a sleep, are waited out once the
        // host is let go: a thread waiting while it holds the host holds out
        // every other thread of the app.
        let paced = if (iface == "gpu/gpu" && func.name == "present")
            || (iface == "time/sleep" && func.name == "sleep-millis")
        {
            "crate::core_app::paced(); "
        } else {
            ""
        };
        let _ = writeln!(
            self.funcs,
            "{{ let st = st.clone(); linker.func_new({key:?}, {name:?}, wasmtime::FuncType::new(&engine, [{p}], [{res}]), \
             move |mut caller, args, rets| {{ let cx = st.cx(); {lifts} \
             let r = {{ let mut h = st.host({only_main}, \"{iface}\")?; {path}::{trait_}::{method}(h.{accessor}(){call_args})? }}; \
             {paced}{lower} Ok(()) }})?; }}",
            name = func.name,
            p = params.join(", "),
            res = results.join(", "),
        );
    }
}
