/* An organisation's IT pack, made in the browser (IC-958 B4): its policy as
 * policy.toml, a macOS configuration profile and a Windows .reg file, set
 * to its name, short name, hub and signing root.
 *
 * A port of scripts/build-policy-templates.py's org_pack(), reading the
 * same key table that script writes (/deploy/policy-keys.json), so the
 * words and the keys live in one place. docs/landing/studio/
 * org-policy-test.mjs runs both on the same inputs and requires the same
 * bytes, and requires this file to rebuild the published samples exactly.
 *
 * Plain functions; nothing leaves the browser.
 */
(function (root) {
  "use strict";

  var DOMAIN = "tech.krate.policy";
  var REG = "Software\\Policies\\Krate";
  // RFC 4122's URL namespace, as Python's uuid.NAMESPACE_URL.
  var NAMESPACE_URL = "6ba7b811-9dad-11d1-80b4-00c04fd430c8";

  /// A name as it may appear in a comment or a plist: no control characters.
  function clean(text) {
    var out = "";
    for (var i = 0; i < text.length; i++) {
      var c = text.charCodeAt(i);
      out += c < 0x20 || c === 0x7f ? " " : text.charAt(i);
    }
    return out;
  }

  function copy(k) {
    var o = {};
    for (var p in k) if (Object.prototype.hasOwnProperty.call(k, p)) o[p] = k[p];
    return o;
  }

  /// KEYS for one organisation, as org_keys() makes them.
  function orgKeys(table, name, slug, hub, roots) {
    var pack = {};
    table.org_pack.forEach(function (tk) { pack[tk[0] + "\u0000" + tk[1]] = true; });
    var values = {};
    values["\u0000version"] = 1;
    values["\u0000name"] = clean(name);
    values["org\u0000slug"] = slug;
    values["trust\u0000roots"] = roots.map(function (r) { return { name: clean(r.name), key: r.key }; });
    values["hub\u0000url"] = hub;
    return table.keys.map(function (k0) {
      var k = copy(k0);
      var at = k.table + "\u0000" + k.key;
      if (pack[at]) k.sample = values[at];
      else {
        if (!("example" in k)) k.example = k.sample;
        k.sample = null;
      }
      return k;
    });
  }

  function sampleDict(keys) {
    var d = {};
    keys.forEach(function (k) {
      if (k.sample === null || k.sample === undefined) return;
      var target = d;
      if (k.table) target = d[k.table] || (d[k.table] = {});
      target[k.key] = k.sample;
    });
    return d;
  }

  // ------------------------------------------------------------- TOML

  function tomlValue(v) {
    if (typeof v === "boolean") return v ? "true" : "false";
    if (typeof v === "number") return String(v);
    if (typeof v === "string") return '"' + v.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
    if (Array.isArray(v)) return "[" + v.map(tomlValue).join(", ") + "]";
    throw new TypeError(String(v));
  }

  function wrap(text, width, prefix) {
    width = width || 76;
    prefix = prefix === undefined ? "# " : prefix;
    var words = String(text).split(/[ \t\n\r\f\v]+/).filter(Boolean), lines = [], line = "";
    words.forEach(function (w) {
      if (line && line.length + 1 + w.length > width - prefix.length) {
        lines.push(prefix + line);
        line = w;
      } else {
        line = line ? line + " " + w : w;
      }
    });
    if (line) lines.push(prefix + line);
    return lines.join("\n");
  }

  /// The [apps] section, commented out (G17): app_rules_toml() in the
  /// generator, line for line.
  function appRulesToml(table) {
    var out = [wrap("Device-side data rules for your organisation's own apps: [apps.\"*\"] for every one of them, or [apps.\"<app id>\"] for one app. Each only narrows; a key left out keeps Krate's default. Uncomment to use."),
      '# [apps."*"]'];
    table.app_rules.forEach(function (r) {
      out.push(wrap(r.help));
      out.push("# " + r.key + " = " + tomlValue(r.narrows));
    });
    out.push('# [apps."' + table.app_rules_example_id + '"]', "# clipboard_write = false", "");
    return out;
  }

  function buildToml(keys, org, table) {
    var out = [
      org ? "# Krate organisation policy, version 1, for " + clean(org) + "." : "# Krate organisation policy, version 1. A sample with every key.",
      "#",
      "# Place it at:",
      "#   Linux    /etc/krate/policy.toml",
      "#   macOS    /Library/Application Support/Krate/policy.toml",
      "#   Windows  %ProgramData%\\Krate\\policy.toml",
      "# A configuration profile (macOS) or Group Policy (Windows) carrying the",
      "# same keys takes precedence over the file. `krate policy` shows which",
      "# one is in force.",
      "#",
      "# A policy only narrows what Krate allows. A key Krate does not know, or",
      "# a value it cannot read, refuses to open apps until it is fixed.",
      "# Generated by scripts/build-policy-templates.py; https://krate.tech/docs/running-in-an-organisation.html",
      "",
    ];
    var current = null;
    keys.forEach(function (k) {
      if (k.table !== current && k.table) {
        current = k.table;
        var shown = keys.some(function (x) { return x.table === current && x.sample !== null && x.sample !== undefined; });
        out.push(shown ? "[" + current + "]" : "# [" + current + "]");
      }
      out.push(wrap(k.help));
      if (k.kind === "roots") {
        out.push("roots = [");
        k.sample.forEach(function (r) { out.push("  { name = " + tomlValue(r.name) + ", key = " + tomlValue(r.key) + " },"); });
        out.push("]");
      } else if (k.sample === null || k.sample === undefined) {
        out.push("# " + k.key + " = " + tomlValue(k.example));
      } else {
        out.push(k.key + " = " + tomlValue(k.sample));
      }
      out.push("");
    });
    if (!org && table && table.app_rules) out = out.concat(appRulesToml(table));
    return out.join("\n").replace(/\s+$/, "") + "\n";
  }

  // ------------------------------------------------------------- plist
  // Python's plistlib.dumps(value, sort_keys=False), exactly.

  function plistEscape(s) {
    // plistlib refuses control characters; clean() has already removed them.
    return s.replace(/\r\n/g, "\n").replace(/\r/g, "\n").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  function plistValue(v, level, out) {
    var pad = new Array(level + 1).join("\t");
    if (typeof v === "string") out.push(pad + "<string>" + plistEscape(v) + "</string>");
    else if (typeof v === "boolean") out.push(pad + (v ? "<true/>" : "<false/>"));
    else if (typeof v === "number") out.push(pad + "<integer>" + String(v) + "</integer>");
    else if (Array.isArray(v)) {
      if (!v.length) { out.push(pad + "<array/>"); return; }
      out.push(pad + "<array>");
      v.forEach(function (x) { plistValue(x, level + 1, out); });
      out.push(pad + "</array>");
    } else {
      var ks = Object.keys(v);
      if (!ks.length) { out.push(pad + "<dict/>"); return; }
      out.push(pad + "<dict>");
      ks.forEach(function (k) {
        out.push(pad + "\t<key>" + plistEscape(k) + "</key>");
        plistValue(v[k], level + 1, out);
      });
      out.push(pad + "</dict>");
    }
  }

  function plist(v) {
    var out = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
      '<plist version="1.0">',
    ];
    plistValue(v, 0, out);
    out.push("</plist>");
    return out.join("\n") + "\n";
  }

  /// uuid.uuid5(NAMESPACE_URL, name), as Python spells it.
  function uuid5(name, subtle) {
    var ns = NAMESPACE_URL.replace(/-/g, "");
    var nsBytes = new Uint8Array(16);
    for (var i = 0; i < 16; i++) nsBytes[i] = parseInt(ns.substr(i * 2, 2), 16);
    var nameBytes = new TextEncoder().encode(name);
    var all = new Uint8Array(16 + nameBytes.length);
    all.set(nsBytes, 0);
    all.set(nameBytes, 16);
    return subtle.digest("SHA-1", all).then(function (buf) {
      var b = new Uint8Array(buf).slice(0, 16);
      b[6] = (b[6] & 0x0f) | 0x50;
      b[8] = (b[8] & 0x3f) | 0x80;
      var h = "";
      for (var j = 0; j < 16; j++) h += (b[j] + 256).toString(16).slice(1);
      return h.slice(0, 8) + "-" + h.slice(8, 12) + "-" + h.slice(12, 16) + "-" + h.slice(16, 20) + "-" + h.slice(20);
    });
  }

  function buildMobileconfig(keys, org, slug, subtle) {
    var at = slug ? "https://krate.tech/org/" + slug + "/krate-policy.mobileconfig" : "https://krate.tech/deploy/krate-policy.mobileconfig";
    return Promise.all([uuid5(at + "#" + DOMAIN, subtle), uuid5(at, subtle)]).then(function (ids) {
      var settings = {};
      settings[DOMAIN] = { Forced: [{ mcx_preference_settings: sampleDict(keys) }] };
      var profile = {
        PayloadContent: [{
          PayloadContent: settings,
          PayloadDisplayName: "Krate organisation policy",
          PayloadIdentifier: DOMAIN + ".settings",
          PayloadType: "com.apple.ManagedClient.preferences",
          PayloadUUID: ids[0],
          PayloadVersion: 1,
        }],
        PayloadDescription: org
          ? "Sets the Krate organisation policy for " + clean(org) + " (tech.krate.policy, version 1)."
          : "Sets the Krate organisation policy (tech.krate.policy, version 1). Replace the sample root key before deploying.",
        PayloadDisplayName: org ? "Krate policy for " + clean(org) : "Krate organisation policy",
        PayloadIdentifier: DOMAIN + ".profile",
        PayloadOrganization: org ? clean(org) : "Krate",
        PayloadScope: "System",
        PayloadType: "Configuration",
        PayloadUUID: ids[1],
        PayloadVersion: 1,
      };
      return plist(profile);
    });
  }

  // --------------------------------------------------------------- .reg

  function regKey(k) { return !k.table ? REG : REG + "\\" + k.table; }
  function regString(s) { return '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"'; }
  function hex2(n) { return (n + 256).toString(16).slice(1); }
  function regMultiSz(values) {
    var data = values.map(function (v) { return v + "\u0000"; }).join("") + "\u0000";
    var out = [];
    for (var i = 0; i < data.length; i++) {
      var c = data.charCodeAt(i);
      out.push(hex2(c & 0xff), hex2(c >> 8));
    }
    return "hex(7):" + out.join(",");
  }

  function buildReg(policyKeys, org, table) {
    var keys = {}, order = [];
    var at = function (key) { if (!keys[key]) { keys[key] = []; order.push(key); } return keys[key]; };
    policyKeys.forEach(function (k) {
      if (k.sample === null || k.sample === undefined) return;
      var key = "HKEY_LOCAL_MACHINE\\" + regKey(k).replace("Software", "SOFTWARE");
      var v = k.sample;
      if (k.kind === "roots") {
        var sub = at(key + "\\roots");
        v.forEach(function (r) { sub.push(regString(r.name) + "=" + regString(r.key)); });
        at(key);
        return;
      }
      var line = regString(k.key) + "=";
      if (k.kind === "bool" || k.kind === "int") line += "dword:" + ("0000000" + Number(v).toString(16)).slice(-8);
      else if (k.kind === "list") line += regMultiSz(v);
      else line += regString(v);
      at(key).push(line);
    });
    var out = ["Windows Registry Editor Version 5.00", "",
      org ? "; Krate organisation policy, version 1, for " + clean(org) + ", as registry values." : "; Krate organisation policy, version 1: the sample policy as registry values.",
      "; For a test computer. Fleets use the ADMX template (krate.admx) instead.",
      org ? "; Generated by scripts/build-policy-templates.py." : "; Replace the sample root key before importing. Generated by scripts/build-policy-templates.py.", ""];
    var depth = function (s) { return s.split("\\").length - 1; };
    order.slice().sort(function (a, b) {
      var d = depth(a) - depth(b);
      return d || (a < b ? -1 : a > b ? 1 : 0);
    }).forEach(function (key) {
      out.push("[" + key + "]");
      keys[key].forEach(function (l) { out.push(l); });
      out.push("");
    });
    if (!org && table && table.app_rules) {
      out.push("; Device-side data rules for every organisation app (remove the ; to use):");
      out.push(";[HKEY_LOCAL_MACHINE\\SOFTWARE\\Policies\\Krate\\apps\\*]");
      table.app_rules.forEach(function (r) {
        out.push(';"' + r.key + '"=dword:' + (r.narrows ? "00000001" : "00000000"));
      });
      out.push("");
    }
    return out.join("\r\n");
  }

  // ------------------------------------------------------------- bytes

  function utf16le(text) {
    var b = new Uint8Array(2 + text.length * 2);
    b[0] = 0xff; b[1] = 0xfe;
    for (var i = 0; i < text.length; i++) {
      var c = text.charCodeAt(i);
      b[2 + i * 2] = c & 0xff;
      b[3 + i * 2] = c >> 8;
    }
    return b;
  }

  /// One organisation's pack: {file name: Uint8Array}, what org_pack()
  /// writes. `table` is /deploy/policy-keys.json.
  function pack(table, opts, subtle) {
    subtle = subtle || (root.crypto && root.crypto.subtle);
    var keys = orgKeys(table, opts.name || opts.slug, opts.slug, opts.hub, opts.roots || []);
    var enc = new TextEncoder();
    return buildMobileconfig(keys, opts.name || opts.slug, opts.slug, subtle).then(function (profile) {
      var out = {};
      out["policy.toml"] = enc.encode(buildToml(keys, opts.name || opts.slug));
      out["krate-policy-" + opts.slug + ".mobileconfig"] = enc.encode(profile);
      out["krate-policy-" + opts.slug + ".reg"] = utf16le(buildReg(keys, opts.name || opts.slug));
      return out;
    });
  }

  /// The published samples, as write() makes them: for the test that this
  /// port is the generator's twin, file for file.
  function samples(table, subtle) {
    subtle = subtle || (root.crypto && root.crypto.subtle);
    var enc = new TextEncoder();
    return buildMobileconfig(table.keys, null, null, subtle).then(function (profile) {
      return {
        "policy.toml": enc.encode(buildToml(table.keys, null, table)),
        "tech.krate.policy.plist": enc.encode(plist(sampleDict(table.keys))),
        "krate-policy.mobileconfig": enc.encode(profile),
        "windows/krate-policy-example.reg": utf16le(buildReg(table.keys, null, table)),
      };
    });
  }

  root.KratePolicy = { pack: pack, samples: samples, clean: clean, DOMAIN: DOMAIN };
})(typeof window !== "undefined" ? window : globalThis);
